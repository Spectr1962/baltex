export const blogRouter = createTRPCRouter({
    // Получить все статьи
    getAll: publicProcedure.query(() => {
        return BLOG_POSTS;
    }),

    // Получить статьи конкретной категории/направления
    getByCategory: publicProcedure
        .input(z.object({ categorySlug: z.string() }))
        .query(({ input }) => {
            return BLOG_POSTS.filter((p) => p.categorySlug === input.categorySlug);
        }),

    // Получить статью по её slug
    getBySlug: publicProcedure
        .input(z.object({ slug: z.string() }))
        .query(({ input }) => {
            const post = BLOG_POSTS.find((p) => p.slug === input.slug);
            return post ?? null;
        })
});
